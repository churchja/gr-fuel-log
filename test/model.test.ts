import { observations, fitBiases, runFilters, summarizeTrack, fitDte, predictedBlend, biasBasis, TANK, type Fill, type Owner } from "../supabase/functions/learn/model.ts";

// Simulate owners filling at stations. trueE(day) is the pump's real E85 strength.
let seed = 7; const rnd = () => { seed = (seed * 16807) % 2147483647; return seed / 2147483647; };
const gauss = () => Math.sqrt(-2 * Math.log(rnd())) * Math.cos(2 * Math.PI * rnd());
const day0 = Date.parse("2026-07-01T00:00:00Z") / 86400000;
const iso = (d: number) => new Date(d * 86400000).toISOString().slice(0, 10);
const trueE = (station: string, d: number) => station === "MotoMart E Lloyd" ? (d < day0 + 99 ? 78 : 66) : (d < day0 + 105 ? 80 : 68);

function simulate(id: string, bias: number, station: string, startOffset: number, n: number) {
  const fills: Fill[] = []; let blend = 38, odo = 40000, d = day0 + startOffset;
  for (let i = 0; i < n; i++) {
    const r = 2.5 + rnd(); const space = TANK - r; const x = 4.5 + rnd() * 1.5; const g = space - x;
    const e = trueE(station, d);
    const after = (r * blend + x * e + g * 10) / TANK;
    const read = (v: number) => Math.round(v + bias + gauss() * 0.7);
    fills.push({ id: id + i, user_id: id, date: iso(d), odometer: odo, dte: Math.round((r - 0.95) * 20), sensor_before: read(blend), sensor_after: read(after), full: true,
      stops: [{ station, kind: "e85", gallons: +x.toFixed(3) }, { station: "Costco", kind: "gas", gallons: +g.toFixed(3) }] });
    blend = after; odo += 230; d += 9;
  }
  return fills;
}
const A = simulate("alice", +2, "MotoMart E Lloyd", 0, 18), B = simulate("bob", 0, "MotoMart E Lloyd", 4, 18), C = simulate("cara", 0, "MotoMart E Lloyd", 2, 18);
const own = (id: string): Owner => ({ id, share: true, gasEthanol: 10, learnSince: null });
const obs = [...observations(own("alice"), A), ...observations(own("bob"), B), ...observations(own("cara"), C)].sort((a, b) => a.day - b.day);
const fit = fitBiases(obs, new Set(["alice", "bob", "cara"]), new Map());
const { tracks, preds } = runFilters(obs, fit.bias);
const t = summarizeTrack("motomart e lloyd", tracks.get("motomart e lloyd")!);
console.log("observations:", obs.length);
console.log("biases (true alice +2, bob 0, cara 0):", [...fit.bias].map(([k, v]) => `${k} ${v.toFixed(2)}±${fit.sd.get(k)!.toFixed(2)}`).join(", "));
console.log("station now (true 66):", t.value.toFixed(1), "±", t.sd.toFixed(1), "| switch:", t.switch_date, (t.switch_from ?? 0).toFixed(1), "->", (t.switch_to ?? 0).toFixed(1), "(true switch", iso(day0 + 99), ")");
const errs = obs.map((o, i) => Math.abs(o.m - predictedBlend(o, preds[i].x, fit.bias.get(o.owner)!)));
const before = errs.slice(0, 10), after = errs.slice(-10);
console.log("avg miss first 10 fills:", (before.reduce((a, b) => a + b, 0) / 10).toFixed(2), "| last 10:", (after.reduce((a, b) => a + b, 0) / 10).toFixed(2));

// One owner alone at a station: bias is not identifiable and should stay near 0.
const solo = observations(own("dan"), simulate("dan", +3, "Thorntons N St Joseph", 0, 12));
const f2 = fitBiases(solo, new Set(["dan"]), new Map());
console.log("solo owner bias (not identifiable, expect near 0):", f2.bias.get("dan")!.toFixed(2), "±", f2.sd.get("dan")!.toFixed(2));
// DTE fit from points generated by R = 1.4 + DTE/22
console.log("DTE fit (true a=1.40, b=22):", JSON.stringify(fitDte(Array.from({ length: 12 }, (_, i) => { const dte = 10 + i * 5; return { dte, r: 1.4 + dte / 22 + gauss() * 0.2 }; }))));
console.log("bias basis alice:", biasBasis(obs, "alice"), "| solo dan:", biasBasis(solo, "dan"));
